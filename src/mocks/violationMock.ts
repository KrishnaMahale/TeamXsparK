export const getViolationSummary = (violations: GridViolation[]): ViolationSummary => {
  const active = violations.filter((v) => v.status === 'active')
  const critical = active.filter((v) => v.severity === 'critical').length
  const warning = active.filter((v) => v.severity === 'warning').length
  const resolved = violations.filter((v) => v.status === 'resolved').length

  return {
    total: active.length,
    critical,
    warning,
    resolved,
    hasViolations: active.length > 0,
  }
}
